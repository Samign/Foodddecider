CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- ── Users ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email       TEXT NOT NULL UNIQUE,
    username    TEXT NOT NULL UNIQUE,
    bio         TEXT,
    image_base  VARCHAR(255),
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS auth_providers (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID UNIQUE,
    provider      TEXT,
    password_hash TEXT
);

CREATE TABLE IF NOT EXISTS followers (
    follower_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    followed_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (follower_id, followed_id)
);

-- ── Lookup tables ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS course_types (
    id            SERIAL PRIMARY KEY,
    name          TEXT UNIQUE NOT NULL,
    display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sources (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug          VARCHAR(255) UNIQUE NOT NULL,
  display_name  VARCHAR(255) NOT NULL,
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- ── Recipes ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS recipes (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            UUID REFERENCES users(id),
    source_id           INT REFERENCES sources(id),
    title               VARCHAR(255) NOT NULL,
    description         TEXT,
    link                TEXT,
    ingredients         TEXT,           -- raw text, used for search_vector only
    is_public           BOOLEAN,
    course_types        INT NOT NULL REFERENCES course_types(id),
    prep_time_minutes   INT CHECK (prep_time_minutes >= 0),
    cook_time_minutes   INT CHECK (cook_time_minutes >= 0),
    total_time_minutes  INT GENERATED ALWAYS AS (
                            COALESCE(prep_time_minutes, 0) +
                            COALESCE(cook_time_minutes, 0)
                        ) STORED,
    image_base          VARCHAR(255),
    servings            INT,
    view_count          INT NOT NULL DEFAULT 0,
    forked_from_recipe_id INT REFERENCES recipes(id) ON DELETE SET NULL,
    fork_count          INT NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    search_vector       tsvector GENERATED ALWAYS AS (
                            setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
                            setweight(to_tsvector('english', coalesce(description, '')), 'B') ||
                            setweight(to_tsvector('english', coalesce(ingredients, '')), 'C')
                        ) STORED
);

CREATE INDEX IF NOT EXISTS recipes_search_idx ON recipes USING GIN(search_vector);

