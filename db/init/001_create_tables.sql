CREATE TABLE IF NOT EXISTS recipe_views (
    id         SERIAL PRIMARY KEY,
    recipe_id  INT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    user_id    UUID REFERENCES users(id) ON DELETE SET NULL,
    session_id TEXT NULL,
    viewed_at  TIMESTAMP DEFAULT NOW(),
    view_hour  TIMESTAMP GENERATED ALWAYS AS (DATE_TRUNC('hour', viewed_at)) STORED
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_user_view
    ON recipe_views (recipe_id, user_id, view_hour)
    WHERE user_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_session_view
    ON recipe_views (recipe_id, session_id, view_hour)
    WHERE session_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS saved_recipes (
    user_id   UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipe_id INT  NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, recipe_id)
);

CREATE TABLE IF NOT EXISTS recipe_steps (
    id          SERIAL,
    recipe_id   INT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    section_id   INT NULL REFERENCES step_sections(id) ON DELETE SET NULL,
    step_number INT NOT NULL,
    content     TEXT NOT NULL,
    PRIMARY KEY (id, recipe_id)
);

CREATE TABLE IF NOT EXISTS step_sections (
    id          SERIAL PRIMARY KEY,
    recipe_id   INT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    title       VARCHAR(255),
    position    INT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_recipe_steps_recipe_id_step
    ON recipe_steps(recipe_id, step_number);

-- ── Tags (optional, kept for future use) ─────────────────────
CREATE TABLE IF NOT EXISTS tags (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,
    slug varchar(50) UNIQUE NOT NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INT NOT NULL DEFAULT 0,
    usage_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tags_slug_prefix ON tags (slug text_pattern_ops); -- for fast prefix searches
CREATE INDEX IF NOT EXISTS idx_tags_featured ON tags (is_featured, display_order) WHERE is_featured; 

CREATE TABLE IF NOT EXISTS recipe_tags (
    recipe_id INT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    tag_id    INT NOT NULL REFERENCES tags(id)    ON DELETE CASCADE,
    PRIMARY KEY (recipe_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_recipe_tags_tag ON recipe_tags(tag_id);

